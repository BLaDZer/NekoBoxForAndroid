package libcore

import (
	"os"
	"path/filepath"
	"sort"
	"testing"

	C "github.com/sagernet/sing-box/constant"
	"github.com/sagernet/sing-box/option"
)

// TestAppConfigsLoad feeds configs shaped like the ones ConfigBuilder.kt emits
// into the real sing-box core (registries + option parsing + box.New). It
// catches removed/renamed config fields, missing registrations and
// constructor-time errors that the Go compiler cannot see after a sing-box
// upgrade. Add a new testdata/*.json whenever ConfigBuilder starts emitting a
// new feature.
func TestAppConfigsLoad(t *testing.T) {
	// The real hooks need the geo databases from the app's assets.
	stub := func(string) ([]option.HeadlessRule, error) {
		return []option.HeadlessRule{{
			Type:           C.RuleTypeDefault,
			DefaultOptions: option.DefaultHeadlessRule{Domain: []string{"example.com"}},
		}}, nil
	}
	geoIPRules, geoSiteRules = stub, stub

	files, err := filepath.Glob("testdata/*.json")
	if err != nil || len(files) == 0 {
		t.Fatalf("no fixtures found: %v", err)
	}
	for _, file := range files {
		file := file
		t.Run(filepath.Base(file), func(t *testing.T) {
			config, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			instance, err := NewSingBoxInstance(string(config), nil)
			if err != nil {
				t.Fatalf("NewSingBoxInstance: %v", err)
			}
			defer instance.Close()

			// Deprecated features are still accepted by this sing-box, but each
			// one is a migration TODO. Surface them; fail on the ones that are
			// scheduled for removal in the next release line (see
			// deprecatedBlocking).
			names := instance.deprecated.Names()
			sort.Strings(names)
			for _, name := range names {
				if deprecatedBlocking[name] {
					t.Errorf("config uses %q, which this sing-box version removes soon", name)
				} else {
					t.Logf("deprecated (migration TODO): %s", name)
				}
			}
		})
	}
}

// deprecatedBlocking lists deprecation notes that must not appear in configs
// generated by the app. Keep empty until a migration is finished, then add the
// note name here so it cannot regress.
var deprecatedBlocking = map[string]bool{}
